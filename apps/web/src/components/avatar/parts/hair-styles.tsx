// パーマのもこもこ。頭のまわりに円を並べて作る
const CURLY_BUMPS = Array.from({ length: 20 }, (_, i) => {
  const angle = (Math.PI * 2 * i) / 20;
  return { cx: 100 + Math.cos(angle) * 64, cy: 92 + Math.sin(angle) * 60 };
}).filter((p) => p.cy < 146);

function Tie({ cx, cy, color, line }: { cx: number; cy: number; color: string; line: string }) {
  return (
    <>
      <circle cx={cx} cy={cy} r={7.5} fill={color} stroke={line} strokeWidth={1.6} />
      <circle cx={cx - 2.2} cy={cy - 2.4} r={2} fill="white" fillOpacity={0.6} />
    </>
  );
}

