function Tie({ cx, cy, color, line }: { cx: number; cy: number; color: string; line: string }) {
  return (
    <>
      <circle cx={cx} cy={cy} r={7} fill={color} stroke={line} strokeWidth={1} />
      <circle cx={cx - 2.2} cy={cy - 2.4} r={2} fill="white" fillOpacity={0.55} />
    </>
  );
}

