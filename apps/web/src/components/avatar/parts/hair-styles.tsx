// 前髪は幅のちがう4〜5本の毛束を片側へ流して、先をとがらせる。耳の高さでは毛先を外へはねさせる。
// 塗りのグラデーション・ツヤ・輪郭線・顔に落ちる影は描画側でつける。
// 座標は半幅 60・頭頂 52 の標準的な輪郭に合わせてあり、描画時に輪郭の大きさへ伸縮する。
// details は毛束の境目のうすい線。accessory は髪ゴムなど、好きな色で塗る小物。
type HairStyle = {
  back?: string;
  front?: string;
  details?: string;
  // 耳の上で外へはねる毛先。前髪の下に描き、付け根を髪の中へ隠す
  flicks?: string;
  frontOpacity?: number;
  accessory?: (color: string, line: string) => React.ReactNode;
};

type Point = [number, number];

// もこもこした毛先（パーマ用）。各点で線が水平になるので、毛先が丸くなる
function waves(from: Point, points: Point[]): string {
  let prev = from;
  let d = "";
  for (const p of points) {
    const mx = (prev[0] + p[0]) / 2;
    d += ` C${mx} ${prev[1]} ${mx} ${p[1]} ${p[0]} ${p[1]}`;
    prev = p;
  }
  return d;
}

